'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const C=require('../assets/career-data.js');
const root=path.resolve(__dirname,'..');
function read(p){return C.parseCSV(fs.readFileSync(path.join(root,p),'utf8'));}
const rb=read('data/career/career_record_batter_2026.csv'),rp=read('data/career/career_record_pitcher_2026.csv');
assert.equal(rb.length,1075);assert.equal(rp.length,559);
assert.equal(new Set(rb.map(r=>r.選手ID)).size,1075);
assert.equal(new Set(rp.map(r=>r.選手ID)).size,559);
assert.ok(rb.every(r=>/^\d{8}$/.test(r.選手ID)));
assert.ok(rp.every(r=>/^\d{8}$/.test(r.選手ID)));
const bm=C.buildBaseline(rb,'batter'),pm=C.buildBaseline(rp,'pitcher');
let batters=C.finalize(bm,'batter'),pitchers=C.finalize(pm,'pitcher');
assert.equal(batters.length,1075);assert.equal(pitchers.length,559);
const by=(rows,name)=>rows.find(p=>p.選手名===name);
const sakamoto=by(batters,'坂本 勇人'),maru=by(batters,'丸 佳浩'),yamazaki=by(pitchers,'山﨑 康晃'),tanaka=by(pitchers,'田中 晴也');
assert.equal(sakamoto.安打,'2474');
assert.equal(sakamoto.犠飛,'62');
assert.ok(C.milestones(sakamoto,'batter').some(x=>x.target===2500&&x.remaining===26));
assert.ok(C.milestones(maru,'batter').some(x=>x.target===2000&&x.remaining===44));
assert.ok(C.milestones(yamazaki,'pitcher').some(x=>x.target===250&&x.remaining===4));
assert.equal(tanaka.先発,'34');
assert.equal(C.outsFromInnings('190.2'),572);
assert.equal(C.inningsFromOuts(572),'190.2');
assert.equal(C.outsFromInnings('+'),0);
assert.equal(C.outsFromInnings('7.1'),22);
assert.equal(C.outsFromInnings('7.2'),23);
assert.throws(()=>C.outsFromInnings('7.3'),/投球回/);
assert.equal(C.parseCSV('id,name\r\n1,"a,b"\r\n2,"c""d"').length,2);
// Adding only the 2027 season must preserve the frozen 2026 snapshots.
const batterBase=maru.安打;
C.applySeason(bm,[{選手ID:maru.選手ID,選手名:maru.選手名,球団名:maru.team,試合:'150',打席:'620',打数:'530',安打:'160',塁打:'270',本塁打:'22',打点:'65',盗塁:'4',四球:'70',死球:'3',犠飛:'4'}],'batter',2027);
const newer=C.finalize(bm,'batter');const newMaru=by(newer,'丸 佳浩');
assert.equal(newMaru.安打,2116);
assert.equal(newMaru.本塁打,314);
assert.equal(newMaru.打率,((1956+160)/(7088+530)).toFixed(3));
assert.notEqual(newMaru.出塁率,'');
assert.equal(maru.安打,batterBase);
C.applySeason(pm,[{選手ID:tanaka.選手ID,選手名:tanaka.選手名,球団名:tanaka.team,登板:'22',先発:'22',投球回:'101.1',自責点:'38',安打:'105',与四球:'21',奪三振:'89',勝利:'8',敗北:'6',セーブ:'0'}],'pitcher',2027);
const newTanaka=by(C.finalize(pm,'pitcher'),'田中 晴也');
assert.equal(newTanaka.登板,56);
assert.equal(newTanaka.先発,56);
assert.equal(newTanaka.投球回,'292');
assert.equal(newTanaka.勝利,14);
assert.equal(newTanaka.防御率,(9*(66+38)/292).toFixed(2));
assert.throws(()=>C.applySeason(C.buildBaseline(rb,'batter'),[{選手ID:'12345678',試合:'10'}],'batter',2027),/年度CSV/);
console.log('PASS: 2026野手1075件・投手559件 / ID・節目・投球回・2027年加算 / 率再計算');